// Publish WHAT THE ENGINE ACTUALLY PLAYS for each wiki-assigned event.
//
// The wiki's sound card parses api.ts for EVENT_FOLEY, the footstep tables and
// bindings.json — but NOT for EVENT_ASSIGNMENTS, so every sound the Game Master
// assigns is invisible to it. He hit that on 2026-08-06: `ui.release` reads
// "no sound yet" on his screen while `ui_click_latch` plays in the game, and it
// looked exactly like his assignment had been reverted. Nothing was reverted;
// the page simply could not see it.
//
// Parsing TypeScript from another agent's build is the fragile way to fix that,
// so the engine publishes the table as DATA instead. Written by this script,
// checked for staleness by verify-quiet, read by anyone who wants to know what
// an event really does.
//
//   node scripts/build-assignments.mjs [--check]
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, "composer", "assignments.json");
const OUT_BEDS = join(ROOT, "composer", "ambience.json");
const api = readFileSync(join(ROOT, "composer", "engine", "api.ts"), "utf8");

const block = api.match(/const EVENT_ASSIGNMENTS: Record<string, EventAssignment\[\]> = \{([\s\S]*?)\n\};/);
if (!block) {
  console.log("FAIL  cannot find EVENT_ASSIGNMENTS in api.ts");
  process.exit(1);
}
const one = (body) => {
  const entry = {};
  const str = (k) => body.match(new RegExp(`${k}:\\s*"([^"]*)"`))?.[1];
  const num = (k) => { const v = body.match(new RegExp(`${k}:\\s*(-?[\\d.]+)`))?.[1]; return v === undefined ? undefined : Number(v); };
  entry.sound = str("sound");
  const take = str("take") ?? num("take");
  if (take !== undefined) entry.take = take;
  for (const k of ["pitch", "volume_db", "max_random_pitch_semis"]) {
    const v = num(k);
    if (v !== undefined) entry[k] = v;
  }
  const bus = str("bus");
  if (bus) entry.bus = bus;
  return entry;
};
const events = {};
// An event holds a LIST — several assigned sounds rotate. `@` is part of an
// id: the wiki scopes an event to one hero as `player.jump@<uid>`, and the
// engine resolves that before the shared name.
for (const m of block[1].matchAll(/"([a-z][\w.@]*)"\s*:\s*\[([\s\S]*?)\],?(?=\n|$)/gi)) {
  const [, id, listBody] = m;
  const sounds = [...listBody.matchAll(/\{([^}]*)\}/g)].map((s) => one(s[1]));
  if (sounds.length) events[id] = sounds;
}
// A DROPPED EVENT MUST NOT BE SILENT. The first version of the list parser
// required a newline after the closing `],`, which the LAST entry in the table
// does not have — so weather.thunder vanished from the manifest while this
// script printed success. That is the dangling-assignment bug in generated
// form: the engine plays a sound nothing can see. Count the keys independently
// and fail if the two disagree.
const declared = [...block[1].matchAll(/^\s{2}"([a-z][\w.@]*)"\s*:\s*\[/gim)].map((m) => m[1]);
const missed = declared.filter((id) => !events[id]);
if (missed.length) {
  console.log(`FAIL  parsed ${Object.keys(events).length} of ${declared.length} assignments — missed: ${missed.join(", ")}`);
  process.exit(1);
}

const doc = {
  format: "pixel-composer-assignments@1",
  _comment:
    "What the composer's engine ACTUALLY plays for each event the Game Master assigned in the wiki " +
    "(EVENT_ASSIGNMENTS in composer/engine/api.ts, generated by scripts/build-assignments.mjs). " +
    "An assignment OUTRANKS EVENT_FOLEY and bindings.json, so this file — not those — is the truth " +
    "for any event listed here. `sound` is a catalog id or composer/<set>, optionally naming ONE " +
    "recording as composer/<set>/<take>, composer/<set>#<take>, or a separate `take` field. Each event maps "+
    "to a LIST: several assigned sounds ROTATE round-robin on that event, each keeping its own "+
    "pitch/volume/jitter. A one-sound event is a list of one.",
  events,
};

// ---- the ambience BEDS the engine really mixes ---------------------------
// Same rule as the assignments, applied to the continuous layer. The wiki used
// to read its ambience rows out of sounds/bindings.json `region.enter`, whose
// map named beds by REGION (cave, coast, plains, meadow) that the engine never
// mixes — so the Game Master was rating and unbinding beds that could not play
// (he rejected ambience.cave#cave_drips on 2026-08-06). That entry is gone now
// because nothing triggers region.enter, and this is what replaces it: the bed
// names read straight out of the engine's setTargets call, so a row can only
// exist for something that actually plays.
const beds = [...(api.match(/this\.ambience\.setTargets\(\{([\s\S]*?)\n\s*\}\);/)?.[1] ?? "")
  .matchAll(/^\s*([a-z][\w]*)\s*:/gim)].map((m) => m[1]);
if (!beds.length) {
  console.log("FAIL  cannot read the ambience beds out of setTargets — fix the regex");
  process.exit(1);
}
const bedDoc = {
  format: "pixel-composer-ambience@1",
  _comment:
    "The looping ambience beds the composer's engine actually mixes, read out of setTargets in " +
    "composer/engine/api.ts. Levels are continuous and driven by sun/weather/terrain, so there is no " +
    "event to assign — but a bed CAN be rated or retired, and this is the only honest list of what is " +
    "playable. A bed not named here does not play, whatever any other file suggests.",
  beds,
};

const next = JSON.stringify(doc, null, 2) + "\n";
const nextBeds = JSON.stringify(bedDoc, null, 2) + "\n";
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(OUT, "utf8"); } catch { /* missing counts as stale */ }
  let curBeds = "";
  try { curBeds = readFileSync(OUT_BEDS, "utf8"); } catch { /* missing counts as stale */ }
  if (cur !== next || curBeds !== nextBeds) {
    console.log("FAIL  composer/assignments.json or ambience.json is stale — run: node scripts/build-assignments.mjs");
    process.exit(1);
  }
  console.log(`  assignments.json in sync (${Object.keys(events).length} assigned events, ${beds.length} ambience beds)`);
} else {
  writeFileSync(OUT, next);
  writeFileSync(OUT_BEDS, nextBeds);
  console.log(`assignments.json → ${Object.keys(events).length} events: ${Object.keys(events).join(", ")}`);
  console.log(`ambience.json    → ${beds.length} beds: ${beds.join(", ")}`);
}
